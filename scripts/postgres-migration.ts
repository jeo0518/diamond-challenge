// npm run db:pg:migration -- <name>
//
// After you change prisma/schema.prisma (and ran `npm run db:migrate` for SQLite),
// run this to create the matching POSTGRES migration for the live site.
// It compares the last generated Postgres schema with the new one — no database needed.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { POSTGRES_SCHEMA, writePostgresSchema } from "./postgres-schema";

const name = (process.argv[2] ?? "").replace(/[^a-z0-9_]+/gi, "_").toLowerCase();
if (!name) {
  console.error("Usage: npm run db:pg:migration -- <short_name>   e.g. npm run db:pg:migration -- add_restaurant_approval");
  process.exit(1);
}

const migrationsDir = "prisma/postgres/migrations";
const hasMigrations = existsSync(migrationsDir);

// The previous Postgres schema (what the live database already has), before regenerating.
const tmp = mkdtempSync(path.join(tmpdir(), "pg-schema-"));
const oldSchemaPath = path.join(tmp, "old.prisma");
if (hasMigrations) writeFileSync(oldSchemaPath, readFileSync(POSTGRES_SCHEMA, "utf8"));

writePostgresSchema();

// Placeholder URLs: `migrate diff` only reads the schema files, it doesn't connect anywhere.
const env = { ...process.env, DATABASE_URL: "postgresql://x@localhost/x", DIRECT_URL: "postgresql://x@localhost/x" };
const sql = execFileSync(
  "npx",
  [
    "prisma", "migrate", "diff",
    ...(hasMigrations ? ["--from-schema-datamodel", oldSchemaPath] : ["--from-empty"]),
    "--to-schema-datamodel", POSTGRES_SCHEMA,
    "--script",
  ],
  { env, encoding: "utf8" },
);

if (!/^\s*(CREATE|ALTER|DROP|INSERT|UPDATE)/m.test(sql)) {
  console.log("No database changes found — nothing to migrate.");
  process.exit(0);
}

const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
const dir = path.join(migrationsDir, `${stamp}_${name}`);
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, "migration.sql"), sql);
writeFileSync(
  path.join(migrationsDir, "migration_lock.toml"),
  '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
);
console.log(`Created ${dir}/migration.sql — commit it. The live site applies it on the next deploy.`);
if (/DROP/.test(sql)) console.log("⚠️  This migration DROPS something. Read it carefully: dropped data is gone for good.");
